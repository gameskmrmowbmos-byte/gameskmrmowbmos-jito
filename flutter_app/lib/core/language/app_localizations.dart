import 'package:flutter/widgets.dart';

enum AppLanguage {
  english('en', 'English', 'EN'),
  hindi('hi', 'हिन्दी', 'HI'),
  marathi('mr', 'मराठी', 'MR');

  const AppLanguage(this.code, this.nativeName, this.shortName);

  final String code;
  final String nativeName;
  final String shortName;

  Locale get locale => Locale(code);

  static AppLanguage fromCode(String? code) {
    for (final language in values) {
      if (language.code == code) return language;
    }
    return AppLanguage.english;
  }
}

class AppLanguageStore {
  AppLanguageStore._();

  static AppLanguage current = AppLanguage.english;
}

class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const delegate = _AppLocalizationsDelegate();

  static const supportedLocales = [
    Locale('en'),
    Locale('hi'),
    Locale('mr'),
  ];

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  String tr(String key, {Map<String, Object?> params = const {}}) {
    return translateForCode(locale.languageCode, key, params: params);
  }

  String? maybeTr(String key, {Map<String, Object?> params = const {}}) {
    return maybeTranslateForCode(locale.languageCode, key, params: params);
  }

  static String trCurrent(
    String key, {
    Map<String, Object?> params = const {},
  }) {
    return translate(AppLanguageStore.current, key, params: params);
  }

  static String translate(
    AppLanguage language,
    String key, {
    Map<String, Object?> params = const {},
  }) {
    return translateForCode(language.code, key, params: params);
  }

  static String localizeDigits(String value, {String? languageCode}) {
    return _applyLocalizedDigits(
      languageCode ?? AppLanguageStore.current.code,
      value,
    );
  }

  static String normalizeDigits(String value) {
    const nativeDigits = '०१२३४५६७८९';
    var normalized = value;
    for (var index = 0; index < nativeDigits.length; index++) {
      normalized = normalized.replaceAll(nativeDigits[index], '$index');
    }
    return normalized;
  }

  static String localizeMarketName(String value, {String? languageCode}) {

    return translations[code]?[value.trim().toUpperCase()] ?? value;
  }

  static String translateForCode(
    String languageCode,
    String key, {
    Map<String, Object?> params = const {},
  }) {
    final table = _translations[languageCode];
    String? text = table?[key];
    if (text == null) {
      final numbered = RegExp(r'^(\d+\.\s*)(.+)$').firstMatch(key);
      if (numbered != null) {
        final prefix = numbered.group(1)!;
        final title = numbered.group(2)!;
        final translatedTitle = table?[title];
        if (translatedTitle != null) text = '$prefix$translatedTitle';
      }
    }
    final resolvedText = text ?? key;
    var result = resolvedText;
    for (final entry in params.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return _applyLocalizedDigits(languageCode, result);
  }

  static String _applyLocalizedDigits(String languageCode, String value) {
    final digitMap = switch (languageCode) {
      'hi' || 'mr' => <String, String>{
          '0': '०',
          '1': '१',
          '2': '२',
          '3': '३',
          '4': '४',
          '5': '५',
          '6': '६',
          '7': '७',
          '8': '८',
          '9': '९',
        },
      _ => null,
    };

    if (digitMap == null) return value;

    var transformed = value;
    for (final entry in digitMap.entries) {
      transformed = transformed.replaceAll(entry.key, entry.value);
    }
    return transformed;
  }

  static String? maybeTranslateForCode(
    String languageCode,
    String key, {
    Map<String, Object?> params = const {},
  }) {
    if (languageCode == AppLanguage.english.code) return key;
    final table = _translations[languageCode];
    if (table == null) return null;
    if (table.containsKey(key)) {
      return translateForCode(languageCode, key, params: params);
    }
    final numbered = RegExp(r'^(\d+\.\s*)(.+)$').firstMatch(key);
    if (numbered != null && table.containsKey(numbered.group(2)!)) {
      return translateForCode(languageCode, key, params: params);
    }
    return null;
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return AppLanguage.values.any(
      (language) => language.code == locale.languageCode,
    );
  }

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) {
    return false;
  }
}

extension AppLocalizationContext on BuildContext {
  String tr(String key, {Map<String, Object?> params = const {}}) {
    return AppLocalizations.of(this).tr(key, params: params);
  }

  String trMaybe(String key, {Map<String, Object?> params = const {}}) {
    return AppLocalizations.of(this).maybeTr(key, params: params) ?? key;
  }
}

